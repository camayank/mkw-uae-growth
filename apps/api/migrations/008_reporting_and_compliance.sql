-- O8 Reporting and compliance calendar: client obligations with evidence, reminder bookkeeping, export log.

-- The calendar date of an instant in Gulf time, for periods, exports and due dates (the session runs in UTC).
create function gulf(t timestamptz) returns date language sql immutable as $$ select (t at time zone 'Asia/Dubai')::date $$;

create table obligations (
  id uuid primary key default gen_random_uuid(),
  client_org_id uuid not null references orgs(id),
  engagement_id uuid references engagements(id),
  kind text not null check (kind in ('licence_renewal', 'visa_expiry', 'vat_return', 'ct_return', 'esr_notification', 'ubo_update', 'audit_filing', 'custom')),
  title text not null,
  basis text not null default '',
  due_date date not null,
  period_label text,
  recurrence text not null default 'none' check (recurrence in ('none', 'monthly', 'quarterly', 'yearly')),
  -- pending_review: generated by rule, a person confirms the date before the client sees it.
  status text not null default 'pending_review' check (status in ('pending_review', 'open', 'evidence_uploaded', 'met', 'waived')),
  confidence text not null default 'UNCERTAIN' check (confidence in ('UNCERTAIN', 'confirmed')),
  confirmed_by uuid references users(id),
  confirmed_at timestamptz,
  evidence_key text,
  evidence_name text,
  evidence_uploaded_by uuid references users(id),
  evidence_uploaded_at timestamptz,
  met_by uuid references users(id),
  met_at timestamptz,
  met_note text,
  waive_reason text,
  reminders_sent int[] not null default '{}',
  previous_id uuid references obligations(id),
  created_by uuid references users(id),
  created_at timestamptz not null default app_now()
);
create index on obligations (client_org_id, due_date);
create index on obligations (status, due_date);

grant all on obligations to app_platform;
alter table obligations enable row level security;
create policy obligations_platform on obligations for all to app_platform using (true) with check (true);
-- The client sees its own obligations once a person has confirmed them (never pending_review, nor a rule-generated
-- date waived before anyone confirmed it), without MKW's notes.
grant select (id, engagement_id, kind, title, basis, due_date, period_label, recurrence, status, confidence, confirmed_at, evidence_name, evidence_uploaded_at, met_at, created_at) on obligations to app_client;
create policy obligations_client on obligations for select to app_client using (client_org_id = app_org() and status <> 'pending_review' and (status <> 'waived' or confidence = 'confirmed'));

-- Accounting exports are logged (range, set, rows) so finance can tie a file to the books later.
create table accounting_exports (
  id uuid primary key default gen_random_uuid(),
  set_name text not null,
  from_date date not null,
  to_date date not null,
  rows int not null,
  exported_by uuid not null references users(id),
  exported_at timestamptz not null default app_now()
);
grant all on accounting_exports to app_platform;
alter table accounting_exports enable row level security;
create policy accounting_exports_platform on accounting_exports for all to app_platform using (true) with check (true);
