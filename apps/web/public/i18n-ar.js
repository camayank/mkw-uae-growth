const SKIP = new Set(["SCRIPT", "STYLE", "CODE", "PRE"]);
const ATTRS = ["placeholder", "title", "aria-label"];

/**
 * Translate a rendered tree in place: text nodes and a few attributes, by exact match or pattern. Text that is
 * a number, a reference, an email or a URL is left as it is. Returns the English strings it could not
 * translate (letters only, so the reviewer sees real gaps and not amounts).
 */
export function translateTree(root, dict = AR, patterns = AR_PATTERNS) {
  const missing = new Set();
  const tr = (text) => {
    const core = text.trim();
    if (!core) return null;
    const hit = dict[core];
    if (hit !== undefined) return text.replace(core, hit);
    for (const [re, fn] of patterns) {
      const m = re.exec(core);
      if (m) return text.replace(core, fn(m));
    }
    if (/^[\d\s.,:%+\-()/·×–—]+$/.test(core) || /@|https?:\/\/|^[A-Z0-9]{8}$|^[A-Z]{2,4}-[A-Z0-9-]+$/.test(core) || /[\u0600-\u06FF]/.test(core)) return null;
    if (/[a-zA-Z]{2,}/.test(core)) missing.add(core);
    return null;
  };
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT, {
    acceptNode: (n) => {
      if (n.nodeType === 1) {
        if (SKIP.has(n.tagName) || n.hasAttribute("data-no-i18n") || n.classList.contains("mono")) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
      return NodeFilter.FILTER_ACCEPT;
    },
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const n of nodes) {
    if (n.nodeType === 3) {
      const out = tr(n.nodeValue);
      if (out !== null) n.nodeValue = out;
    } else {
      for (const a of ATTRS) {
        if (n.hasAttribute(a)) {
          const out = tr(n.getAttribute(a));
          if (out !== null) n.setAttribute(a, out);
        }
      }
      if (n.tagName === "INPUT" && (n.type === "submit" || n.type === "button") && n.value) {
        const out = tr(n.value);
        if (out !== null) n.value = out;
      }
    }
  }
  return [...missing];
}
